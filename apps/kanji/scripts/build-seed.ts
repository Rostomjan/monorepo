#!/usr/bin/env bun
/**
 * Build the Convex seed-data module from authored content files.
 * Content files (apps/kanji/content/level-N/*.json) are the source of truth;
 * this script validates them against the locked field set and emits
 * packages/backend/convex/kanjiSeedData.ts (deterministic output).
 *
 * Usage: bun scripts/build-seed.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const CONTENT = join(ROOT, "content");
const OUT = join(ROOT, "..", "..", "packages", "backend", "convex", "kanjiSeedData.ts");

const TYPES = ["radical", "kanji", "vocabulary"] as const;

interface ContentSubject {
  glyph: string;
  type: (typeof TYPES)[number];
  level: number;
  meanings: string[];
  readings: string[];
  mnemonic: string;
  components: string[];
  audioRef: string | null;
  examples: Array<{ text: string; reading: string; gloss: string }>;
  sources: string[];
  shipped: boolean;
}

function isSubject(v: unknown): v is ContentSubject {
  if (typeof v !== "object" || v === null) return false;
  const o = v as Record<string, unknown>;
  return (
    typeof o.glyph === "string" &&
    o.glyph.length > 0 &&
    TYPES.includes(o.type as (typeof TYPES)[number]) &&
    typeof o.level === "number" &&
    Array.isArray(o.meanings) &&
    (o.meanings as unknown[]).length > 0 &&
    Array.isArray(o.readings) &&
    typeof o.mnemonic === "string" &&
    (o.mnemonic as string).length > 0 &&
    Array.isArray(o.components) &&
    (o.audioRef === null || typeof o.audioRef === "string") &&
    Array.isArray(o.examples) &&
    Array.isArray(o.sources) &&
    (o.sources as unknown[]).length > 0 &&
    typeof o.shipped === "boolean"
  );
}

function main(): void {
  const subjects: ContentSubject[] = [];
  const levels = readdirSync(CONTENT, { withFileTypes: true })
    .filter((e) => e.isDirectory() && e.name.startsWith("level-"))
    .map((e) => e.name)
    .sort();
  for (const level of levels) {
    const dir = join(CONTENT, level);
    for (const file of readdirSync(dir).sort()) {
      if (!file.endsWith(".json")) continue;
      const parsed: unknown = JSON.parse(readFileSync(join(dir, file), "utf8"));
      if (!Array.isArray(parsed)) throw new Error(`${level}/${file}: top level must be an array`);
      parsed.forEach((item, i) => {
        if (!isSubject(item)) {
          throw new Error(`${level}/${file}[${i}]: fails content validation`);
        }
        subjects.push(item);
      });
    }
  }
  const shipped = subjects.filter((s) => s.shipped);
  const body = `/**
 * GENERATED by apps/kanji/scripts/build-seed.ts — do not edit by hand.
 * Source of truth: apps/kanji/content/level-N/*.json
 */
export interface SeedSubject {
  glyph: string;
  type: "radical" | "kanji" | "vocabulary";
  level: number;
  meanings: string[];
  readings: string[];
  mnemonic: string;
  components: string[];
  audioRef: string | null;
  examples: Array<{ text: string; reading: string; gloss: string }>;
  sources: string[];
  shipped: boolean;
}

export const SEED_SUBJECTS: SeedSubject[] = ${JSON.stringify(subjects, null, 2)};
`;
  writeFileSync(OUT, body);
  console.log(
    `seed data: ${subjects.length} subjects (${shipped.length} shipped) -> packages/backend/convex/kanjiSeedData.ts`,
  );
}

main();
