// Frozen TS truth (bun, full 17-digit doubles) — the first three mulberry32
// draws for seed 42. Mirrors python's test_rng_reference_points_frozen_from_ts.
var rngReference = []float64{
	0.6011037519201636,
	0.44829055899754167,
	0.8524657934904099,
}

func TestRNGReferencePointsFrozenFromTS(t *testing.T) {
	rng := newMulberry32(42)
	for i, want := range rngReference {
		if got := rng.next(); got != want {
			t.Fatalf("draw %d: got %.17g, want %.17g (must be bit-identical to TS)", i+1, got, want)
		}
	}
}

// TestSameSeedSameCatalogAsTS locks the Go generateCatalog to the TS truth
// in testdata/catalog-42.json (generated by bun from
// apps/ichiba/src/lib/catalog.ts generateCatalog(40, 30, 42)). This is the
// byte-for-byte fixture parity contract from docs/BACKEND_TWINS.md.
func TestSameSeedSameCatalogAsTS(t *testing.T) {
	raw, err := os.ReadFile("testdata/catalog-42.json")
	if err != nil {
		t.Fatalf("missing TS golden fixture: %v", err)
	}
	var golden struct {
		Shops    []Shop    `json:"shops"`
		Products []Product `json:"products"`
	}
	if err := json.Unmarshal(raw, &golden); err != nil {
		t.Fatalf("golden fixture does not parse: %v", err)
	}

	shops, products := generateCatalog(40, 30, 42)
	if len(shops) != len(golden.Shops) || len(products) != len(golden.Products) {
		t.Fatalf("size drift: %d shops / %d products, want %d / %d",
			len(shops), len(products), len(golden.Shops), len(golden.Products))
	}
	for i, shop := range shops {
		if shop != golden.Shops[i] {
			t.Fatalf("shop %d drift:\n got %#v\nwant %#v", i, shop, golden.Shops[i])
		}
	}
	for i, product := range products {
		if product != golden.Products[i] {
			t.Fatalf("product %d drift:\n got %#v\nwant %#v", i, product, golden.Products[i])
		}
	}
}

func TestCatalogInvariants(t *testing.T) {
	shops, products := generateCatalog(40, 30, 42)
	if len(shops) != 40 || len(products) != 40*30 {
		t.Fatalf("expected 40 shops × 30 products, got %d/%d", len(shops), len(products))
	}
	for _, p := range products {
		if p.PriceYen < 500 || p.PriceYen >= 500+20000 {
			t.Fatalf("priceYen %d out of JPY range", p.PriceYen)
		}
		if p.Stock < 1 || p.Stock > 50 {
			t.Fatalf("stock %d out of range", p.Stock)
		}
	}
}

func TestLikePatternEscapesMetacharacters(t *testing.T) {
	// 100% match TS likePattern() / python like_pattern():
	// %, _ and \ inside user input stay literals.
	want := `%50\%\_a\\b%`
	if got := likePattern(`50%_a\b`); got != want {
		t.Fatalf("likePattern = %q, want %q", got, want)
	}
	if got := likePattern(""); got != "%%" {
		t.Fatalf("empty input = %q, want %q", got, "%%")
	}
}
